/**
 * راه‌های تماس صفحهٔ «پشتیبانی» (دکمهٔ «پشتیبانی» بالای چهار صفحهٔ اصلی ← زبانهٔ «تماس با ما») — تنها نقطهٔ تنظیم (از ۱.۷.۷).
 *
 * وضعیت فعلی (۱.۸.۰): فقط «ربات تلگرام» پشتیبانی فعال است (ApartemantSupportBot).
 * ایمیل، تلفن و بله فعلاً خالی‌اند؛ زیر ردیف تلگرام یک خط «مسیرهای ارتباطی دیگر به‌زودی راه‌اندازی می‌شود.» نمایش داده می‌شود.
 * هر وقت راه دیگری راه افتاد، فقط مقدارش را اینجا بنویسید؛ ردیفش خودکار اضافه می‌شود.
 *
 * چطور پر کنید: مقدارها را همین‌جا بنویسید و برنامه را دوباره build کنید (README ← «پشتیبانی»). هیچ فایل دیگری لازم نیست.
 *  - email    : نشانی ایمیل، مثل  support@your-domain.ir
 *  - phone    : شمارهٔ تلفن، مثل  09121234567  یا  +989121234567  (فقط شماره‌گیر باز می‌شود؛ خودش تماس نمی‌گیرد)
 *  - bale     : شناسهٔ بله بدون @، مثل  my_bale_id  (یا  @my_bale_id  یا  ble.ir/my_bale_id)
 *  - telegram : شناسهٔ ربات/حساب تلگرام بدون @، مثل  my_tg_id  (یا  @my_tg_id  یا  t.me/my_tg_id)
 *
 * قاعده‌ها:
 *  - مقدار خالی ('') یا نامعتبر = همان ردیف نمایش داده نمی‌شود.
 *  - اگر هر چهار خالی باشند، زبانهٔ «تماس با ما» فقط کارت «به‌زودی» نشان می‌دهد و موضوع راهنمای «پشتیبانی» پنهان است (زبانهٔ «سؤال‌های رایج» همیشه هست).
 *  - هیچ مقدار نمونه/ساختگی نباید اینجا یا در بستهٔ نهایی باشد؛ فقط مقدارهای واقعی (آزمون `support177` این را بررسی می‌کند).
 */
